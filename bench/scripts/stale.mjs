/* Устарел ли посчитанный диф пары относительно её снимков.

   diff.mjs пропускает пару, у которой на диске есть картинка различий и годная запись в
   report.json. Само по себе это нужно — прогон продолжается с места остановки, когда
   истёк serve_url. Но пересъёмка стороны этого пропуска не отменяла: числа оставались от
   прежнего снимка, и отличить такой прогон от честного было нельзя ничем, кроме памяти
   человека о том, что он переснимал. bench/README.md предупреждал об этом текстом дважды,
   хотя времена обоих снимков и своей картинки инструменту известны.

   Возвращает причину строкой (её печатают рядом с парой, чтобы пересчёт был виден) или
   null, если пересчитывать не из-за чего.

   Сравниваются времена PNG, а JSON стороны (rects и ошибки съёмки) — нет: shoot.mjs пишет
   его вместе со снимком, поэтому отдельного случая «JSON свежее PNG» не бывает, а пара с
   пометкой shootErrors и непеременившимися снимками должна остаться пропущенной вместе со
   своей пометкой.

   Отсутствующий файл — не «устарел»: снимка нет — решает ветка «нет снимка app/kit»,
   она называет причину точнее; картинки дифа нет — пара и так пересчитывается. Поэтому
   statSync здесь не бросает, а молчит. Равенство времён — тот же прогон, а не
   пересъёмка: иначе пара пересчитывалась бы на каждом запуске. */
import { statSync } from 'node:fs'

const mtimeMs = (file) => {
  try {
    return statSync(file).mtimeMs
  } catch {
    return null
  }
}

export function staleReason(diffFile, appPath, kitPath) {
  const diff = mtimeMs(diffFile)
  if (diff === null) return null
  const newer = [
    ['app', appPath],
    ['kit', kitPath]
  ].filter(([, file]) => {
    const m = mtimeMs(file)
    return m !== null && m > diff
  })
  if (newer.length === 0) return null
  const sides = newer.map(([side]) => side).join(' и ')
  return `${newer.length > 1 ? 'снимки' : 'снимок'} ${sides} новее дифа`
}

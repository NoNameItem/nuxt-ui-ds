/* DOM extracted from Kbd.vue — element nesting and data-slot names as shipped. */
const tree = [{"t":"div","s":"base"}];

const render = createRenderer('kbd', kbdTheme, tree);

/* Kbd.vue renders `value` through its shortcut alias map. */
const KEYS = {
  meta: '⌘', command: '⌘', ctrl: '⌃', control: '⌃', alt: '⌥', option: '⌥', shift: '⇧',
  enter: '↵', backspace: '⌫', delete: '⌦', escape: '⎋', esc: '⎋', tab: '⇥', capslock: '⇪',
  arrowup: '↑', arrowdown: '↓', arrowleft: '←', arrowright: '→', pageup: '⇞', pagedown: '⇟', home: '↖', end: '↘'
};

export function Kbd(props) {
  const { value, children, ...rest } = props;
  const label = value !== undefined ? (KEYS[String(value).toLowerCase()] ?? value) : children;
  return render({ ...rest, base: label });
}

register('Kbd', Kbd);

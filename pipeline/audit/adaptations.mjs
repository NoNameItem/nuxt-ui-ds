/* Осознанные расхождения кита с темой библиотеки. Это не дефекты: каждое
   введено раундами правок 6 и 7 и проверено глазами. Приёмка обязана их знать,
   иначе они всплывают на каждом компоненте с оверлеем — 872 расхождения на
   живом прогоне. */

/* 1. Компонент живёт внутри рамки артборда, а не во вьюпорте: fixed заменён
   на absolute (раунд 6). Замену именно проверяем, а не игнорируем: если
   позиционирование потеряно совсем, absolute не окажется в DOM и расхождение
   останется. */
const POSITION = { fixed: 'absolute' }

/* 2. Вьюпортные единицы в произвольных значениях заменены процентами от рамки
   (раунд 6): w-[calc(100vw-2rem)] → w-[calc(100%-2rem)], h-svh → h-full.
   Применяется только к ожиданию темы (см. adaptSets) — DOM кита сравнивается
   как есть, иначе подмена, которую кит не сделал, никогда не всплывёт. */
/* Минимумы — исключение (24.09): процентный min-height от родителя с высотой auto
   равен нулю, и панель, которой тема библиотеки задаёт `min-h-svh` или
   `min-h-[calc(100vh-var(--ui-header-height))]`, схлопывается. Минимум поэтому держит
   вьюпортную единицу, и это вьюпорт самого артборда: каждый артборд — свой документ.
   Кит пишет `min-h-[100dvh]` и `min-h-[calc(100dvh-…)]`. Основание — пиксели, а не код
   кита: пары error, main, dashboard-panel--* и dashboard-sidebar--* в ноль в обеих темах.
   Правила у этих классов в tokens кита нет — значение он ставит инлайновым стилем, — и
   это отдельный пункт проверки 3, адаптацией он не закрывается. */
const MINIMUM = /^((?:[^:[\]]+:)*)(min-[hw])-(.+)$/
const viewport = (c) => {
  const m = MINIMUM.exec(c)
  if (m) {
    const [, variant, prefix, rest] = m
    const unit = prefix === 'min-w' ? '100dvw' : '100dvh'
    if (/^(?:svh|dvh|lvh|vh|vw|screen)$/.test(rest)) return `${variant}${prefix}-[${unit}]`
    return c.replace(/100(?:s|l|d)?vh/g, '100dvh').replace(/100(?:s|l|d)?vw/g, '100dvw')
  }
  return c
    .replace(/100vw/g, '100%')
    .replace(/100dvh/g, '100%')
    .replace(/100vh/g, '100%')
    .replace(/^h-(?:svh|dvh|lvh)$/, 'h-full')
}

/* 3. Классы с произвольным свойством кит выносит в инлайновый style через
   extractVarClasses(): в атрибуте class их нет по построению, сравнивать
   нечего. */
export const isVarClass = (c) => c.includes('[--')

/* Адаптируем только ожидание. Симметричная нормализация делала невидимым
   обратный случай — кит оставил вместо адаптированного класса что-то третье:
   обе стороны схлопывались в одно и то же, и проверка молчала. Потеря класса при
   этом по-прежнему расхождение: в `got` его просто нет.

   Библиотечный класс, который у кита стоит как есть, засчитывается без адаптации.
   Раньше библиотечный `fixed` у кита считался расхождением («кит адаптацию не
   применил»), но раунды 114-115 (keepFixed) сознательно вернули `fixed` на
   `content` у Drawer, Slideover и Modal и на `viewport` у Toaster: у absolute иначе
   растеризуется глиф, и пары стенда сошлись в ноль только с `fixed`. Старое правило
   давало на свежей копии кита 76 ложных расхождений ровно на этих слотах (Drawer 29,
   Slideover 29, Toaster 15, Modal 3 — `100vw` той же природы) при нулевых пикселях
   стенда (сверка 24.09). Кит, адаптирующий и не адаптирующий,
   теперь оба верны; неверен только третий класс или его отсутствие. */
export function adaptSets(got, want) {
  const g = [...new Set(got.filter((c) => !isVarClass(c)))].sort()
  const has = new Set(g)
  const w = [...new Set(want.map((c) => (has.has(c) ? c : POSITION[c] || viewport(c))).filter((c) => !isVarClass(c)))].sort()
  return { got: g, want: w }
}
